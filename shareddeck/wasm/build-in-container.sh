#!/bin/bash
# Builds shareddeck-module.wasm. Runs inside the FlyByWire dev-env container (see build.sh).
set -e

SDK=/workdir/MSFS_SDK
SRC=/external/wasm/src
OUT=/external/package/shareddeck-module/modules
TMP=/tmp/shareddeck-build

mkdir -p "$OUT" "$TMP"

# key event id -> name table, generated from the SDK so names stay correct for this SDK version
awk 'BEGIN { print "// generated by build-in-container.sh - do not edit"; print "#pragma once"; print "struct KeyEventName { unsigned int id; const char* name; };"; print "static const KeyEventName kKeyEventNames[] = {" }
     /^#define KEY_[A-Z0-9_]+[ \t]+\(KEY_ID_MIN[ \t]*\+[ \t]*[0-9]+\)/ {
       name = $2; sub(/^KEY_/, "", name)
       if (name != "ID_MIN" && name != "ID_MAX") printf "  {%s, \"%s\"},\n", $2, name
     }
     END { print "};" }' "$SDK/WASM/include/MSFS/Legacy/gauges.h" > "$SRC/KeyEventNames.generated.h"

FLAGS="-std=c++20 -Wall -Wextra -Wno-unused-function -Wno-unused-command-line-argument -Wno-ignored-attributes -Wno-macro-redefined \
  -target wasm32-unknown-wasi --sysroot $SDK/WASM/wasi-sysroot -mthread-model single -fno-exceptions -fms-extensions \
  -fvisibility=hidden -ffunction-sections -fdata-sections -Werror=return-type -fno-stack-protector -fstack-size-section -mbulk-memory \
  -O2 -flto -DNDEBUG -D_MSFS_WASM=1 -D__wasi__ -D_LIBC_NO_EXCEPTIONS -D_LIBCPP_HAS_NO_THREADS -D_WINDLL -D_MBCS -DNOMINMAX \
  -D_FILE_OFFSET_BITS=64 -DJSON_NOEXCEPTION -DJSON_HAS_FILESYSTEM=0 -DJSON_HAS_EXPERIMENTAL_FILESYSTEM=0 \
  -I$SDK/WASM/include -I$SDK/WASM/wasi-sysroot/include -I$SDK/WASM/wasi-sysroot/include/c++/v1 \
  -I\"$SDK/SimConnect SDK/include\" -I/external/wasm/third_party"

eval clang++ $FLAGS -c "$SRC/SharedDeck.cpp" -o "$TMP/SharedDeck.o"

wasm-ld -O2 --lto-O2 --strip-debug --no-entry --allow-undefined --export __wasm_call_ctors --export-dynamic \
  --export malloc --export free --export mallinfo --export mchunkit_begin --export mchunkit_next \
  --export get_pages_state --export mark_decommit_pages --export-table --gc-sections \
  -lc++ -lc++abi -L$SDK/WASM/wasi-sysroot/lib/wasm32-wasi -lc $SDK/WASM/wasi-sysroot/lib/wasm32-wasi/libclang_rt.builtins-wasm32.a \
  "$TMP/SharedDeck.o" -o "$TMP/shareddeck-module.wasm"

wasm-opt -O1 --signext-lowering -o "$OUT/shareddeck-module.wasm" "$TMP/shareddeck-module.wasm"

echo "built $OUT/shareddeck-module.wasm"
